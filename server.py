def audio_library_key(
    title: str, text: str, voice: str, kind: str, book_id: str, speak_title: bool = True,
    provider: str = "local", model: str = "",
) -> str:
    """Identify the exact performance request across browsers and server restarts."""
    identity = {
        "model": model if provider == "gemini" else LOCAL_TTS_MODEL,
        "title": title,
        "text": text,
        "voice": voice,
        "kind": kind,
        "book": book_id,
    }
    # Keep the existing local-Qwen library addressable. Gemini is already
    # separated by its model name, and naming the provider makes that explicit.
    if provider == "gemini":
        identity["provider"] = provider
        # Generation settings affect whether a reading is complete. Bump this
        # when those settings change so an older, truncated render is not reused.
        identity["pipelineVersion"] = GEMINI_TTS_PIPELINE_VERSION
    if not speak_title:
        identity["speakTitle"] = False
    # The role is what the key has always carried, so a rebound role would other-
    # wise keep serving readings performed by the voice it used to point at. Name
    # the voice as well, but only once it stops being that role's default, so the
    # library built up under the defaults stays addressable.
    resolved = GEMINI_TTS_VOICES.get(voice) if provider == "gemini" else resolve_local_voice(voice)
    defaults = GEMINI_TTS_VOICES if provider == "gemini" else DEFAULT_TTS_VOICES
    if resolved and resolved != defaults.get(voice):
        identity["voiceName"] = resolved
    return hashlib.sha256(
        json.dumps(identity, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def cache_audio(filename: str, audio: bytes, key: str | None = None, metadata: dict | None = None) -> str:
    """Persist one reading and return a stable, human-named media path."""
    name = SAFE_FILENAME.sub(" ", filename).strip().strip(".")
    name = re.sub(r"\s+", " ", name)[:120] or "reading"
    if not name.lower().endswith(".wav"):
        name += ".wav"

    token = key or secrets.token_urlsafe(9)
    AUDIO_CACHE[token] = (name, audio)
    while len(AUDIO_CACHE) > AUDIO_CACHE_LIMIT:
        AUDIO_CACHE.popitem(last=False)
    if key:
        AUDIO_LIBRARY_PATH.mkdir(exist_ok=True)
        temporary = AUDIO_LIBRARY_PATH / f"{key}.tmp"
        with AUDIO_LIBRARY_LOCK:
            temporary.write_bytes(audio)
            temporary.replace(AUDIO_LIBRARY_PATH / f"{key}.wav")
            metadata_path = AUDIO_LIBRARY_PATH / f"{key}.json"
            try:
                record = json.loads(metadata_path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                record = {}
            if not isinstance(record, dict):
                record = {}
            record.update(metadata or {})
            record['filename'] = name
            metadata_temp = metadata_path.with_suffix('.json.tmp')
            metadata_temp.write_text(json.dumps(record, ensure_ascii=False), encoding='utf-8')
            metadata_temp.replace(metadata_path)
    return f"/api/tts/audio/{token}/{quote(name)}"


def stitch_wav_files(paths: list[Path]) -> bytes:
    """Join compatible PCM WAV recordings without transcoding or quality loss."""
    if not paths:
        raise ValueError("At least one saved audio part is required.")
    parameters = None
    frames = []
    for path in paths:
        with wave.open(str(path), "rb") as source:
            current = (source.getnchannels(), source.getsampwidth(), source.getframerate(), source.getcomptype())
            if parameters is None:
                parameters = current
            elif current != parameters:
                raise ValueError("The saved parts use incompatible WAV formats.")
            frames.append(source.readframes(source.getnframes()))
    output = io.BytesIO()
    with wave.open(output, "wb") as target:
        target.setnchannels(parameters[0])
        target.setsampwidth(parameters[1])
        target.setframerate(parameters[2])
        target.setcomptype(parameters[3], "not compressed")
        target.writeframes(b"".join(frames))
    return output.getvalue()


def stitched_audio_key(part_keys: list[str]) -> str:
    identity = json.dumps({"kind": "stitched-chapter", "parts": part_keys}, separators=(",", ":"))
    return hashlib.sha256(identity.encode("utf-8")).hexdigest()


class PoetryRequestHandler(SimpleHTTPRequestHandler):
    """Static-file handler with small, allow-listed FLUX and model reverse proxies."""

    def do_HEAD(self) -> None:  # noqa: N802 - stdlib handler API
        if self.path.split('?', 1)[0] == '/library.html':
            self.path = '/index.html'
        if self.path.startswith("/api/tts/audio/"):
            self._serve_cached_audio()
            return
        super().do_HEAD()

    def do_GET(self) -> None:  # noqa: N802 - stdlib handler API
        if self.path.split('?', 1)[0] == '/library.html':
            # Both entry URLs load the same shell; history navigation keeps
            # the narration element alive instead of loading another document.
            self.path = '/index.html'
        if self.path.startswith("/api/tts/jobs/"):
            job_id = self.path.rsplit("/", 1)[-1]
            with TTS_JOBS_LOCK:
                job = TTS_JOBS.get(job_id)
                snapshot = dict(job) if job else None
            self._send_json(200 if snapshot else 404, snapshot or {"error": "Queue not found. Retry to reuse saved parts."})
            return
        if self.path.rstrip("/") == "/images":
            self.path = "/images.html"
            super().do_GET()
            return
        if self.path.rstrip("/") == "/voices":
            self.path = "/voices.html"
            super().do_GET()
            return
        if self.path == "/api/tts/voices":
            self._list_tts_voices()
            return
        if self.path == "/api/image-library":
            self._list_image_library()
            return
        if self.path.startswith("/api/flux/"):
            upstream_path = self.path.removeprefix("/api/flux")
            if upstream_path in ALLOWED_GET_PATHS or upstream_path.startswith("/images/"):
                self._proxy_flux("GET", upstream_path)
            else:
                self.send_error(404, "Unknown FLUX endpoint")
            return
        if self.path.startswith("/api/chat/"):
            upstream_path = self.path.removeprefix("/api/chat")
            if upstream_path in ALLOWED_CHAT_GET_PATHS:
                self._proxy_chat("GET", upstream_path)
            else:
                self.send_error(404, "Unknown model endpoint")
            return
        if self.path.startswith("/api/tts/audio/"):
            self._serve_cached_audio()
            return
        if self.path == "/api/poems":
            self._list_user_poems()
            return
        super().do_GET()

    def do_PUT(self) -> None:  # noqa: N802 - stdlib handler API
        if self.path == "/api/tts/roles":
            self._assign_tts_voice()
            return
        if self.path.startswith("/api/poems/"):
            self._update_user_poem(self.path.removeprefix("/api/poems/"))
            return
        self.send_error(405, "PUT is only supported for the shared shelf and narration voices")

    def do_DELETE(self) -> None:  # noqa: N802 - stdlib handler API
        if self.path == "/api/image-library":
            self._delete_library_images()
            return
        if self.path.startswith("/api/poems/"):
            self._delete_user_poem(self.path.removeprefix("/api/poems/"))
            return
        self.send_error(405, "DELETE is only supported for the shared shelf")

    @staticmethod
    def _image_manifest() -> dict:
        try:
            payload = json.loads(IMAGE_LIBRARY_PATH.read_text(encoding="utf-8"))
        except (FileNotFoundError, json.JSONDecodeError):
            return {}
        return payload if isinstance(payload, dict) else {}

    @staticmethod
    def _write_image_manifest(manifest: dict) -> None:
        IMAGE_LIBRARY_PATH.parent.mkdir(exist_ok=True)
        temporary = IMAGE_LIBRARY_PATH.with_suffix(".json.tmp")
        temporary.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        temporary.replace(IMAGE_LIBRARY_PATH)

    def _list_image_library(self) -> None:
        with IMAGE_LIBRARY_LOCK:
            manifest = self._image_manifest()
        metadata = image_poem_metadata()
        images = []
        for poem_id, records in manifest.items():
            for record in records if isinstance(records, list) else []:
                filename = str(record.get("filename", ""))
                if filename.startswith("poem-images/assets/"):
                    images.append({"poemId": poem_id, **metadata.get(poem_id, {}), **record})
        self._send_json(200, {"images": images})

    def _save_library_image(self) -> None:
        """Copy a completed FLUX image into the shared, durable image library."""
        try:
            payload = self._read_json_body()
            if not isinstance(payload, dict):
                raise ValueError('Provide an image record.')
            poem_id, filename = str(payload.get('poemId', '')), str(payload.get('filename', ''))
            if not re.fullmatch(r'[a-f0-9]{1,8}', poem_id) or not re.fullmatch(r'[A-Za-z0-9_-][A-Za-z0-9_.-]*\.(?:png|jpg|jpeg|webp)', filename, re.I):
                raise ValueError('Provide a poem identifier and an image filename.')
            identity = hashlib.sha256(f'{poem_id}:{filename}'.encode()).hexdigest()
            relative = f'poem-images/assets/{identity}{Path(filename).suffix.lower()}'
            with IMAGE_LIBRARY_LOCK:
                manifest = self._image_manifest()
                existing = next((r for r in manifest.get(poem_id, []) if r.get('filename') == relative), None)
                try:
                    deleted = json.loads(IMAGE_DELETIONS_PATH.read_text())
                except (OSError, ValueError):
                    deleted = []
                if f'image:{poem_id}:{filename}' in deleted:
                    self._send_json(200, {'deleted': True})
                    return
            if existing and (BASE_DIR / relative).is_file():
                self._send_json(200, {'image': existing})
                return
            headers = {'X-API-Key': FLUX_API_KEY or self.headers.get('X-API-Key', '')}
            request = Request(f'{FLUX_BASE_URL}/images/{quote(filename)}', headers=headers)
            with urlopen(request, timeout=30) as response:
                if not response.headers.get('Content-Type', '').startswith('image/'):
                    raise ValueError('The image server did not return an image.')
                data = response.read(32 * 1024 * 1024 + 1)
                if len(data) > 32 * 1024 * 1024:
                    raise ValueError('Image exceeds the shared library size limit.')
            record = {k: str(payload.get(k, ''))[:12000] for k in ('prompt', 'style', 'poemTitle', 'collection')}
            record.update(filename=relative, originalFilename=filename, status='done')
            with IMAGE_LIBRARY_LOCK:
                try:
                    deleted = json.loads(IMAGE_DELETIONS_PATH.read_text())
                except (OSError, ValueError):
                    deleted = []
                if f'image:{poem_id}:{filename}' in deleted:
                    self._send_json(200, {'deleted': True})
                    return
                IMAGE_ASSETS_PATH.mkdir(parents=True, exist_ok=True)
                (BASE_DIR / relative).write_bytes(data)
                manifest = self._image_manifest()
                records = manifest.setdefault(poem_id, [])
                if not any(r.get('filename') == relative for r in records):
                    records.append(record)
                self._write_image_manifest(manifest)
            self._send_json(200, {'image': record})
        except (ValueError, json.JSONDecodeError) as error:
            self._send_json(400, {'error': str(error)})
        except (URLError, OSError) as error:
            self._send_json(502, {'error': f'Could not save shared image: {error}'})

    def _delete_library_images(self) -> None:
        try:
            requested = self._read_json_body().get("images", [])
        except json.JSONDecodeError:
            self._send_json(400, {"error": "The deletion request was not valid JSON."})
            return
        targets = {
            (str(item.get("poemId", "")), str(item.get("filename", "")))
            for item in requested if isinstance(item, dict)
        }
        if not targets:
            self._send_json(400, {"error": "Select at least one image to delete."})
            return

        deleted = []
        with IMAGE_LIBRARY_LOCK:
            manifest = self._image_manifest()
            try:
                tombstones = set(json.loads(IMAGE_DELETIONS_PATH.read_text(encoding="utf-8")))
            except (FileNotFoundError, json.JSONDecodeError, TypeError):
                tombstones = set()
            for poem_id, filename in targets:
                relative = filename.removeprefix("poem-images/assets/")
                if not filename.startswith("poem-images/assets/") or Path(relative).name != relative:
                    continue
                records = manifest.get(poem_id, [])
                for record in records:
                    if record.get('filename') == filename and record.get('originalFilename'):
                        tombstones.add(f"image:{poem_id}:{record['originalFilename']}")
                kept = [record for record in records if record.get("filename") != filename]
                if len(kept) == len(records):
                    continue
                if kept:
                    manifest[poem_id] = kept
                else:
                    manifest.pop(poem_id, None)
                try:
                    (IMAGE_ASSETS_PATH / relative).unlink()
                except FileNotFoundError:
                    pass
                deleted.append(filename)
                tombstones.add(poem_id)
            self._write_image_manifest(manifest)
            tombstone_temp = IMAGE_DELETIONS_PATH.with_suffix(".json.tmp")
            tombstone_temp.write_text(json.dumps(sorted(tombstones), indent=2) + "\n", encoding="utf-8")
            tombstone_temp.replace(IMAGE_DELETIONS_PATH)
        self._send_json(200, {"deleted": deleted})

