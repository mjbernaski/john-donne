def tts_provider_error(error: HTTPError, api_key: str = "") -> str:
    """Keep actionable provider messages without exposing credentials or raw bodies."""
    message = ""
    try:
        payload = json.loads(error.read())
        detail = payload.get("error", payload) if isinstance(payload, dict) else {}
        message = detail.get("message", "") if isinstance(detail, dict) else ""
        if not isinstance(message, str):
            message = ""
        if isinstance(detail, dict) and detail.get("code") == "content_blocked":
            message = "Gemini declined this passage (content_blocked): " + message
    except (ValueError, OSError):
        pass
    for secret in (api_key, GEMINI_API_KEY):
        if secret:
            message = message.replace(secret, "[redacted]")
    message = re.sub(r"AIza[\w-]+", "[redacted]", message)
    message = " ".join(message.split())[:1000]
    return f"Provider returned HTTP {error.code}" + (f": {message}" if message else ".")


